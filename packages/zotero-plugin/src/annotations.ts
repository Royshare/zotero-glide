/**
 * Annotation geometry and the JSON Zotero stores. Pure, unit-tested.
 *
 * Zotero keeps an annotation's position in PDF space: `{pageIndex, rects: [[x1, y1, x2, y2], ...]}` with the
 * origin bottom-left and y up. The helper reports text geometry in page space (origin top-left, y down, after
 * the page's own rotation/crop) and gives, per page, the matrix `m` that maps PDF space to page space; so
 * saving inverts `m` and drawing applies it. The sort index format and colors mirror Zotero's own reader
 * (reader.js `getSortIndex`): `pageIndex(5)|charOffset(6)|top(5)`, where `top = pageHeight - highestY`.
 */

import type { Matrix, PageInfo, Rect } from "./protocol.ts";

export type AnnotationKind = "highlight" | "underline" | "note";

/** [x1, y1, x2, y2] in PDF space, x1<x2, y1<y2 */
export type PdfRect = [number, number, number, number];

/** Zotero's default annotation colors, in the order its reader shows them. */
export const ANNOTATION_COLORS: ReadonlyArray<{ name: string; hex: string }> = [
  { name: "Yellow", hex: "#ffd400" },
  { name: "Red", hex: "#ff6666" },
  { name: "Green", hex: "#5fb236" },
  { name: "Blue", hex: "#2ea8e5" },
  { name: "Purple", hex: "#a28ae5" },
  { name: "Magenta", hex: "#e56eee" },
  { name: "Orange", hex: "#f19837" },
  { name: "Gray", hex: "#aaaaaa" },
];
export const DEFAULT_ANNOTATION_COLOR = ANNOTATION_COLORS[0]!.hex;

export function applyMatrix(m: Matrix, x: number, y: number): [number, number] {
  return [m[0] * x + m[2] * y + m[4], m[1] * x + m[3] * y + m[5]];
}

export function invertMatrix(m: Matrix): Matrix {
  const det = m[0] * m[3] - m[1] * m[2];
  if (Math.abs(det) < 1e-12) throw new Error("singular page matrix");
  const a = m[3] / det;
  const b = -m[1] / det;
  const c = -m[2] / det;
  const d = m[0] / det;
  return [a, b, c, d, -(a * m[4] + c * m[5]), -(b * m[4] + d * m[5])];
}

/** Transforms a rect's four corners and returns their axis-aligned bounds as [minX, minY, maxX, maxY]. */
function boundsOf(m: Matrix, x0: number, y0: number, x1: number, y1: number): [number, number, number, number] {
  const pts = [applyMatrix(m, x0, y0), applyMatrix(m, x1, y0), applyMatrix(m, x0, y1), applyMatrix(m, x1, y1)];
  const xs = pts.map((p) => p[0]);
  const ys = pts.map((p) => p[1]);
  return [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
}

/** Page-space `[x, y, w, h]` rects -> PDF-space `[x1, y1, x2, y2]` rects (what Zotero stores). */
export function pageRectsToPdf(rects: Rect[], pageMatrix: Matrix): PdfRect[] {
  const inv = invertMatrix(pageMatrix);
  return rects.map(([x, y, w, h]) => boundsOf(inv, x, y, x + w, y + h).map(round3) as PdfRect);
}

/** PDF-space rects (an existing Zotero annotation) -> page-space `[x, y, w, h]` rects for drawing. */
export function pdfRectsToPage(rects: PdfRect[], pageMatrix: Matrix): Rect[] {
  return rects.map(([x1, y1, x2, y2]) => {
    const [bx0, by0, bx1, by1] = boundsOf(pageMatrix, x1, y1, x2, y2);
    return [bx0, by0, bx1 - bx0, by1 - by0] as Rect;
  });
}

const round3 = (v: number): number => Math.round(v * 1000) / 1000;
const pad = (n: number, width: number): string => Math.max(0, Math.floor(n)).toString().slice(0, width).padStart(width, "0");

/**
 * Zotero's sort index. `charOffset` is the index of the selection's first character in the page's text
 * (ours, not PDF.js's: it only has to order annotations within a page); `top` is the distance from the top
 * of the page to the highest point of the annotation, in PDF points.
 */
export function sortIndex(pageIndex: number, charOffset: number, pdfRects: PdfRect[], page: PageInfo): string {
  const highest = pdfRects.length ? Math.max(...pdfRects.map((r) => r[3])) : 0;
  const [, y0, , y1] = boundsOf(invertMatrix(page.m), 0, 0, page.w, page.h);
  const top = Math.max(0, y1 - y0 - highest);
  return [pad(pageIndex, 5), pad(charOffset, 6), pad(top, 5)].join("|");
}

/** The position object Zotero stores in `annotationPosition`. */
export interface AnnotationPosition {
  pageIndex: number;
  rects: PdfRect[];
}

/** What `Zotero.Annotations.saveFromJSON` takes (minus `key`, generated by the caller). */
export interface AnnotationDraft {
  type: AnnotationKind;
  text?: string;
  comment: string;
  color: string;
  pageLabel: string;
  sortIndex: string;
  position: AnnotationPosition;
  tags: Array<{ name: string }>;
}

export interface MarkupInput {
  kind: "highlight" | "underline";
  text: string;
  comment?: string;
  color: string;
  pageIndex: number;
  pageLabel: string;
  /** selection rectangles, page space [x, y, w, h] */
  pageRects: Rect[];
  charOffset: number;
  page: PageInfo;
}

export function buildMarkup(i: MarkupInput): AnnotationDraft {
  const rects = pageRectsToPdf(i.pageRects, i.page.m);
  return {
    type: i.kind,
    text: i.text,
    comment: i.comment ?? "",
    color: i.color,
    pageLabel: i.pageLabel,
    sortIndex: sortIndex(i.pageIndex, i.charOffset, rects, i.page),
    position: { pageIndex: i.pageIndex, rects },
    tags: [],
  };
}

/** Zotero's sticky-note size, in points. */
export const NOTE_SIZE = 22;

export interface NoteInput {
  comment: string;
  color: string;
  pageIndex: number;
  pageLabel: string;
  /** where the user clicked, page space */
  x: number;
  y: number;
  page: PageInfo;
}

export function buildNote(i: NoteInput): AnnotationDraft {
  const half = NOTE_SIZE / 2;
  const rects = pageRectsToPdf([[i.x - half, i.y - half, NOTE_SIZE, NOTE_SIZE]], i.page.m);
  return {
    type: "note",
    comment: i.comment,
    color: i.color,
    pageLabel: i.pageLabel,
    sortIndex: sortIndex(i.pageIndex, 0, rects, i.page),
    position: { pageIndex: i.pageIndex, rects },
    tags: [],
  };
}

export interface ImageInput {
  comment?: string;
  color: string;
  pageIndex: number;
  pageLabel: string;
  /** the selected area, page space [x, y, w, h] */
  pageRect: Rect;
  page: PageInfo;
}

/** An area ("image") annotation; the bitmap itself is stored separately in Zotero's annotation cache. */
export function buildImage(i: ImageInput): AnnotationDraft {
  const rects = pageRectsToPdf([i.pageRect], i.page.m);
  return {
    type: "image",
    comment: i.comment ?? "",
    color: i.color,
    pageLabel: i.pageLabel,
    sortIndex: sortIndex(i.pageIndex, 0, rects, i.page),
    position: { pageIndex: i.pageIndex, rects },
    tags: [],
  };
}

/** Parses Zotero's stored position JSON defensively (a malformed one must not break rendering the page). */
export function parsePosition(json: string): AnnotationPosition | null {
  try {
    const p = JSON.parse(json) as { pageIndex?: unknown; rects?: unknown };
    if (typeof p.pageIndex !== "number" || !Array.isArray(p.rects)) return null;
    const rects = p.rects.filter(
      (r): r is PdfRect => Array.isArray(r) && r.length === 4 && r.every((v) => typeof v === "number" && Number.isFinite(v))
    );
    return rects.length ? { pageIndex: p.pageIndex, rects } : null;
  } catch {
    return null;
  }
}

/** Colors drawn with the mix-blend the way Zotero draws them: markup is translucent so the text stays legible. */
export function overlayStyle(kind: AnnotationKind, hex: string): { background?: string; borderBottom?: string; opacity: number } {
  if (kind === "highlight") return { background: hex, opacity: 0.4 };
  if (kind === "underline") return { borderBottom: `2px solid ${hex}`, opacity: 1 };
  if (kind === "image") return { opacity: 1 };
  return { background: hex, opacity: 0.9 };
}

/** `#rrggbb` -> [r, g, b] in 0..1 (the helper's export wants this); falls back to Zotero yellow. */
export function hexToRgb(hex: string): [number, number, number] {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex.trim());
  const v = m ? parseInt(m[1]!, 16) : 0xffd400;
  return [((v >> 16) & 255) / 255, ((v >> 8) & 255) / 255, (v & 255) / 255];
}
