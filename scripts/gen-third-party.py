"""Generates THIRD_PARTY_NOTICES.md: every third-party component that ends up in a
shipped build, with its license and the license text.

  python3 scripts/gen-third-party.py            # rewrite THIRD_PARTY_NOTICES.md
  python3 scripts/gen-third-party.py --check    # exit 1 if the file is out of date (CI)

Covers: (1) every Rust crate in the build graph of each shipped target (union of the
four triples), with license files read from the crate sources; (2) the libraries MuPDF
compiles from its own vendored tree; (3) bundled fonts and icons. The Rust part needs
the crates fetched (`cargo fetch --locked` in packages/reader-helper).
"""
import glob, hashlib, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HELPER = f"{ROOT}/packages/reader-helper"
OUT = f"{ROOT}/THIRD_PARTY_NOTICES.md"
TARGETS = ["aarch64-apple-darwin", "x86_64-apple-darwin", "x86_64-pc-windows-msvc", "x86_64-unknown-linux-gnu"]
LICENSE_FILE_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "UNLICENSE", "NOTICE")

# Libraries MuPDF's build compiles from its vendored thirdparty/ directory for this project's
# feature set (mupdf default-features = false, features = ["base14-fonts"]; brotli, mujs,
# extract, tesseract, leptonica, curl, gumbo, zxing are NOT compiled).
MUPDF_THIRDPARTY = [
    ("freetype", "FreeType License (FTL) or GPL-2.0", ["LICENSE.TXT"]),
    ("harfbuzz", "MIT (Old MIT)", ["COPYING"]),
    ("jbig2dec", "AGPL-3.0-or-later", ["COPYING"]),
    ("lcms2", "MIT", ["LICENSE"]),
    ("libjpeg", "IJG (Independent JPEG Group) license", []),  # the vendored copy omits the README: see IJG_README
    ("openjpeg", "BSD-2-Clause", ["LICENSE"]),
    ("zlib", "Zlib", ["LICENSE"]),
]

# MuPDF's vendored libjpeg (IJG 9f) omits the README that carries the IJG license, but the license requires that
# README to accompany any distribution of the source. A verbatim copy of the README from the IJG 9f release
# (https://www.ijg.org/files/jpegsrc.v9f.tar.gz) is kept in licenses/ and shipped with the source archive.
IJG_README = f"{ROOT}/licenses/libjpeg-ijg-9f-README.txt"
# Things a release must still resolve; printed in the generated file so they cannot be forgotten.
KNOWN_GAPS: list[str] = []

def cargo_metadata(target):
    out = subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
                         cwd=HELPER, capture_output=True, text=True)
    if out.returncode:
        sys.exit(f"cargo metadata failed for {target}: {out.stderr[:300]}")
    return json.loads(out.stdout)

def read(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.read().strip()

def crate_license_files(pkg):
    d = os.path.dirname(pkg["manifest_path"])
    files = sorted(p for p in glob.glob(f"{d}/*") if os.path.isfile(p)
                   and os.path.basename(p).upper().startswith(LICENSE_FILE_PREFIXES))
    return [(os.path.basename(p), read(p)) for p in files]

def mupdf_dir(pkgs):
    for p in pkgs.values():
        if p["name"] == "mupdf-sys":
            return os.path.join(os.path.dirname(p["manifest_path"]), "mupdf")
    sys.exit("mupdf-sys not found in build graph")

def main():
    pkgs, used = {}, set()
    for t in TARGETS:
        meta = cargo_metadata(t)
        by_id = {p["id"]: p for p in meta["packages"]}
        for n in meta["resolve"]["nodes"]:
            used.add(n["id"]); pkgs[n["id"]] = by_id[n["id"]]
    crates = sorted((p for p in pkgs.values() if p["name"] != "fast-reader-helper"), key=lambda p: (p["name"], p["version"]))

    texts = {}  # sha -> (title, text, [users])
    def add_text(label, name, text):
        h = hashlib.sha256(" ".join(text.split()).encode()).hexdigest()
        texts.setdefault(h, (name, text, []))[2].append(label)

    lines = ["# Third-party notices", "",
             "Zotero Fast Reader is licensed under **AGPL-3.0-or-later** (see `LICENSE`). It includes or",
             "links the third-party components below. This file is generated by",
             "`scripts/gen-third-party.py`; do not edit by hand.", "",
             "## MuPDF (statically linked into `fast-reader-helper`)", "",
             "MuPDF (c) Artifex Software, Inc., licensed under the GNU Affero General Public License, version 3",
             "or (at your option) any later version. It is built from the source vendored in the `mupdf-sys`",
             "crate and statically linked; that is why this whole project is AGPL-3.0-or-later. Its complete",
             "corresponding source is included in the source archive attached to every release",
             "(see `SOURCE.md`).", "",
             "Libraries compiled from MuPDF's own vendored `thirdparty/` tree:", "",
             "| Library | License |", "|---|---|"]
    md = mupdf_dir(pkgs)
    for name, lic, files in MUPDF_THIRDPARTY:
        lines.append(f"| {name} | {lic} |")
        if name == "libjpeg":
            add_text("libjpeg (MuPDF)", "libjpeg (IJG 9f) -- README, verbatim", read(IJG_README))
        for f in files:
            p = f"{md}/thirdparty/{name}/{f}"
            if os.path.exists(p):
                add_text(f"{name} (MuPDF)", f"{name} -- {f}", read(p))
            else:
                sys.exit(f"missing license file: {p}")
    lines += ["", "**This software is based in part on the work of the Independent JPEG Group.** (Required by the IJG",
              "license when only executable code is distributed. The full IJG README is reproduced below.)"]
    if KNOWN_GAPS:
        lines += ["", "**Known gaps (must be resolved before a public release):**", ""] + [f"- {g}" for g in KNOWN_GAPS]
    lines += ["", "Bundled fonts: the URW++ base-14 \"Nimbus\" fonts (c) 2014 URW++ Design & Development, compiled",
              "into MuPDF (`base14-fonts` feature) and distributed with MuPDF under the AGPL (with the fonts'",
              "own font exception). No other fonts are bundled.", "",
              "## Icons", "", "The reader UI's icons are inlined SVG paths from **Lucide** (https://lucide.dev),",
              "(c) Lucide Contributors, ISC License; portions derived from Feather (c) Cole Bemis, MIT License.", ""]
    add_text("Lucide icons", "Lucide -- ISC License", LUCIDE_LICENSE)
    add_text("Feather (via Lucide)", "Feather -- MIT License", FEATHER_LICENSE)

    lines += ["## Rust crates", "",
              f"Union of the build graphs of: {', '.join(TARGETS)}.", "",
              "| Crate | Version | License (as declared) |", "|---|---|---|"]
    no_file = []
    for p in crates:
        lines.append(f"| {p['name']} | {p['version']} | {p['license'] or 'see crate'} |")
        files = crate_license_files(p)
        if not files:
            no_file.append(f"{p['name']} {p['version']} ({p['license'] or 'undeclared'})")
        for fname, text in files:
            add_text(f"{p['name']} {p['version']}", fname, text)

    if no_file:
        lines += ["", "Crates whose published package contains no license file (their declared license applies; the",
                  "standard text of it is reproduced below where another crate ships it, and for MuPDF in `LICENSE`):", ""]
        lines += [f"- {x}" for x in no_file]
    lines += ["", "## License texts", "",
              "Identical texts are listed once, with the components that use them.", ""]
    for h, (title, text, users) in sorted(texts.items(), key=lambda kv: kv[1][2][0].lower()):
        lines += [f"### {title}", "", "Used by: " + ", ".join(sorted(set(users))), "", "```text", text, "```", ""]
    new = "\n".join(lines).rstrip() + "\n"
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != new:
            sys.exit("THIRD_PARTY_NOTICES.md is out of date: run python3 scripts/gen-third-party.py")
        print("THIRD_PARTY_NOTICES.md is up to date")
    else:
        open(OUT, "w").write(new)
        print(f"wrote {OUT}: {len(crates)} crates, {len(texts)} distinct license texts")

